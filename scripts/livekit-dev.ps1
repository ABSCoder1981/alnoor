<#
.SYNOPSIS
  Runs a local LiveKit server for development (PRD section 22.1) and configures the API to use it.

.DESCRIPTION
  1. Downloads the pinned livekit-server release into .tools/ (git-ignored) and verifies its SHA-256.
  2. Creates a random development API key/secret once and keeps it in .env (git-ignored).
  3. Stores LiveKit:Url / ApiKey / ApiSecret in the API's `dotnet user-secrets` (never in appsettings).
  4. Starts livekit-server on all interfaces so phones on the same Wi-Fi can connect.

  Development only. Not for production: --dev mode is insecure by design.

.EXAMPLE
  ./scripts/livekit-dev.ps1
  ./scripts/livekit-dev.ps1 -NodeIp 192.168.1.20   # if the detected Wi-Fi address is wrong
#>
[CmdletBinding()]
param(
    [string]$NodeIp
)

$ErrorActionPreference = 'Stop'

$Version = '1.13.11'
$Sha256 = '5d071ea43339f0140d24a66f0b2ff8a7bf6c4d0dceb19b30abca835670213667'   # livekit_1.13.11_windows_amd64.zip
$RepoRoot = Split-Path -Parent $PSScriptRoot
$ToolDir = Join-Path $RepoRoot ".tools\livekit\$Version"
$Exe = Join-Path $ToolDir 'livekit-server.exe'
$EnvFile = Join-Path $RepoRoot '.env'
$ApiProject = Join-Path $RepoRoot 'backend\src\ALNoor.Api'

# --- 1. Download and verify ---------------------------------------------------
if (-not (Test-Path $Exe)) {
    New-Item -ItemType Directory -Force -Path $ToolDir | Out-Null
    $zip = Join-Path $ToolDir 'livekit.zip'
    $url = "https://github.com/livekit/livekit/releases/download/v$Version/livekit_${Version}_windows_amd64.zip"
    Write-Host "Downloading livekit-server $Version ..."
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    Invoke-WebRequest -Uri $url -OutFile $zip -UseBasicParsing
    $actual = (Get-FileHash -Algorithm SHA256 $zip).Hash.ToLowerInvariant()
    if ($actual -ne $Sha256) {
        Remove-Item $zip -Force
        throw "Checksum mismatch for $url (expected $Sha256, got $actual). Download deleted."
    }
    Expand-Archive -Path $zip -DestinationPath $ToolDir -Force
    Remove-Item $zip -Force
}

# --- 2. Development keys (kept in .env, which is git-ignored) ----------------
function Get-EnvValue([string]$name) {
    if (-not (Test-Path $EnvFile)) { return $null }
    $line = Get-Content $EnvFile | Where-Object { $_ -match "^\s*$name=" } | Select-Object -First 1
    if ($null -eq $line) { return $null }
    return ($line -split '=', 2)[1].Trim()
}

$apiKey = Get-EnvValue 'LIVEKIT_DEV_API_KEY'
$apiSecret = Get-EnvValue 'LIVEKIT_DEV_API_SECRET'
if ([string]::IsNullOrWhiteSpace($apiKey) -or [string]::IsNullOrWhiteSpace($apiSecret)) {
    $bytes = New-Object byte[] 32
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $apiKey = 'alnoor-dev'
    $apiSecret = [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
    Add-Content -Path $EnvFile -Encoding ascii -Value @(
        '',
        '# Local livekit-server keys (generated by scripts/livekit-dev.ps1; development only)',
        "LIVEKIT_DEV_API_KEY=$apiKey",
        "LIVEKIT_DEV_API_SECRET=$apiSecret"
    )
    Write-Host "Generated development LiveKit keys in .env"
}

# --- 3. Address that phones on the same Wi-Fi can reach ----------------------
if ([string]::IsNullOrWhiteSpace($NodeIp)) {
    $route = Get-NetRoute -DestinationPrefix '0.0.0.0/0' -ErrorAction SilentlyContinue |
        Sort-Object RouteMetric | Select-Object -First 1
    if ($null -ne $route) {
        $NodeIp = (Get-NetIPAddress -InterfaceIndex $route.InterfaceIndex -AddressFamily IPv4 |
            Select-Object -First 1).IPAddress
    }
    if ([string]::IsNullOrWhiteSpace($NodeIp)) { $NodeIp = '127.0.0.1' }
}
$liveKitUrl = "ws://${NodeIp}:7880"

# --- 4. Configure the API through user-secrets --------------------------------
$dotnet = Get-Command dotnet -ErrorAction SilentlyContinue
if ($null -eq $dotnet) { $dotnetPath = 'C:\Program Files\dotnet\dotnet.exe' } else { $dotnetPath = $dotnet.Source }
& $dotnetPath user-secrets --project $ApiProject set 'LiveKit:Url' $liveKitUrl | Out-Null
& $dotnetPath user-secrets --project $ApiProject set 'LiveKit:ApiKey' $apiKey | Out-Null
& $dotnetPath user-secrets --project $ApiProject set 'LiveKit:ApiSecret' $apiSecret | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Could not store LiveKit settings in dotnet user-secrets.' }

Write-Host ""
Write-Host "LiveKit dev server: $liveKitUrl   (API user-secrets updated; restart the API if it is running)"
Write-Host "Android on the same Wi-Fi: API base URL http://${NodeIp}:5080"
Write-Host "If Windows Firewall asks, allow livekit-server on PRIVATE networks only."
Write-Host "Press Ctrl+C to stop."
Write-Host ""

# Keys go through the environment, not the command line, so they don't show in process listings.
$env:LIVEKIT_KEYS = "${apiKey}: ${apiSecret}"
# Rooms are created only by the API (PRD 14.4). Without this, an old token could re-create an ended class's room.
& $Exe --dev --bind 0.0.0.0 --node-ip $NodeIp --config-body "room:`n  auto_create: false"
