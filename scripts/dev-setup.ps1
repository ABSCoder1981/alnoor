<#
.SYNOPSIS
  One-time (repeatable) development setup for the API's secrets.

.DESCRIPTION
  Stores in the API's `dotnet user-secrets` (never in appsettings or Git):
    - ConnectionStrings:Default  for the local PostgreSQL (native install or docker compose)
    - Jwt:SigningKey              random 48 bytes, generated once and kept in .env
  Reads passwords from .env (git-ignored). Development only.

.EXAMPLE
  ./scripts/dev-setup.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$RepoRoot = Split-Path -Parent $PSScriptRoot
$EnvFile = Join-Path $RepoRoot '.env'
$ApiProject = Join-Path $RepoRoot 'backend\src\ALNoor.Api'

function Get-EnvValue([string]$name) {
    if (-not (Test-Path $EnvFile)) { return $null }
    $line = Get-Content $EnvFile | Where-Object { $_ -match "^\s*$name=" } | Select-Object -First 1
    if ($null -eq $line) { return $null }
    return ($line -split '=', 2)[1].Trim()
}

function New-RandomBase64([int]$bytes) {
    $buffer = New-Object byte[] $bytes
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
    return [Convert]::ToBase64String($buffer)
}

# Native PostgreSQL install uses POSTGRES_APP_PASSWORD; docker compose uses POSTGRES_PASSWORD.
$dbPassword = Get-EnvValue 'POSTGRES_APP_PASSWORD'
if ([string]::IsNullOrWhiteSpace($dbPassword)) { $dbPassword = Get-EnvValue 'POSTGRES_PASSWORD' }
if ([string]::IsNullOrWhiteSpace($dbPassword)) { throw 'No database password in .env (POSTGRES_APP_PASSWORD or POSTGRES_PASSWORD). See README.' }
$dbUser = Get-EnvValue 'POSTGRES_USER'; if ([string]::IsNullOrWhiteSpace($dbUser)) { $dbUser = 'alnoor' }
$dbName = Get-EnvValue 'POSTGRES_DB'; if ([string]::IsNullOrWhiteSpace($dbName)) { $dbName = 'alnoor_dev' }
$dbPort = Get-EnvValue 'POSTGRES_PORT'; if ([string]::IsNullOrWhiteSpace($dbPort)) { $dbPort = '5432' }

$jwtKey = Get-EnvValue 'JWT_DEV_SIGNING_KEY'
if ([string]::IsNullOrWhiteSpace($jwtKey)) {
    $jwtKey = New-RandomBase64 48
    Add-Content -Path $EnvFile -Encoding ascii -Value @('', '# API access-token signing key (generated by scripts/dev-setup.ps1; development only)', "JWT_DEV_SIGNING_KEY=$jwtKey")
    Write-Host 'Generated a development JWT signing key in .env'
}

$dotnet = Get-Command dotnet -ErrorAction SilentlyContinue
if ($null -eq $dotnet) { $dotnetPath = 'C:\Program Files\dotnet\dotnet.exe' } else { $dotnetPath = $dotnet.Source }

$connection = "Host=localhost;Port=$dbPort;Database=$dbName;Username=$dbUser;Password=$dbPassword"
& $dotnetPath user-secrets --project $ApiProject set 'ConnectionStrings:Default' $connection | Out-Null
& $dotnetPath user-secrets --project $ApiProject set 'Jwt:SigningKey' $jwtKey | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Could not store settings in dotnet user-secrets.' }

Write-Host 'API user-secrets updated: ConnectionStrings:Default, Jwt:SigningKey'
Write-Host 'Next: cd backend; dotnet tool restore; dotnet ef database update --project src/ALNoor.Api'
